    s = io.open(p, encoding="utf-8", newline="").read()
    eol = "\r\n" if "\r\n" in s else "\n"
    ok = True
    for old, new in reps:
        oldn = old.replace("\n", eol)
        newn = new.replace("\n", eol)
        if oldn not in s:
            log.append(f"MISS {fn}: {old[:50]!r}")
            ok = False
            continue
        s = s.replace(oldn, newn, 1)
    if ok:
        s = re.sub(r"^updated: .*$", "updated: 2026-09-02", s, count=1, flags=re.M)
