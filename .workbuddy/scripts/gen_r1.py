def _band_ranges(sel, b_):
    """返回某难度层的**连续题号区间**列表（如 [(1,2),(5,7)]）。

    用于卷头「难度总览」表。2026-09-18 新增：旧版只印 `idx[0]–idx[-1]`，
    当同层题号**不连续**时（如基础 1,2 与 5）会印出「1–5」这种**虚报覆盖**的区间，
    误导使用者「3、4 也是基础题」。改为按连续段拆分，多段用「、」连接。
    """
    idx = [i + 1 for i, c in enumerate(sel) if c["band"] == b_]
    if not idx:
        return ""
    segs, st, prev = [], idx[0], idx[0]
    for x in idx[1:]:
        if x == prev + 1:
            prev = x
            continue
        segs.append((st, prev))
        st = prev = x
    segs.append((st, prev))
    return "、".join(str(a) if a == b2 else str(a) + "–" + str(b2) for a, b2 in segs)


