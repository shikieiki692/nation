def clean_used(used, src):
    r"""清理 `used_in` → 可印在卷面的「曾用于」条目（**供 gen_r1 与 gen_r1_mixed 共用**）。

    `used_in` 是 YAML 列表或字符串，内含两类**库内杂质**（用户投诉的「无关信息」）：
      ① **库内路径**（`04-题库/…`、`04-课件/习题集/…`、裸 `04-题库/化学原理阶段测试卷`）；
      ② **与「来源：」行重复的书目名**（`shortsrc(r)`）→ 卷面冗余。
    只保留**人类可读的卷名**并去重。

    ⚠️ 判库内路径**不能只认「以 `/` 或行首开头」**——实测 `, 04-题库/化学原理阶段测试卷`
    逗号后跟空格（`re.split` 后已 strip，故 OK），但也存在 `xx/04-课件/…` 中段形态。
    故用**宽松判据**：条目中**任意位置**出现 `0N-`（N∈0..9）编号前缀即视为库内路径。
    ⚠️ 但书目名本身可能含数字（如 `第一轮综合卷06`）→ 故须**紧跟 `-`**（`0\d-` 或 `\d\d-`）
    且该 `-` 前是**非汉字/非字母**的边界（行首或 `/` 或空格），避免误伤卷名中的数字。
    """
    if used in ("", "[]"):
        return ""
    _us = used.replace('"', "").replace("[", "").replace("]", "")
    _keep = []
    for _x in re.split(r"[,，]\s*", _us):
        _x = _x.strip()
        if not _x:
            continue
        # 库内路径：以 `NN-`（NN 为两位数字）开头，或路径段 `/NN-` 开头
        if re.match(r"^\d\d-", _x) or re.search(r"(?:^|/)\d\d-[^\s]", _x):
            continue
        if _x == src:
            continue
        if _x not in _keep:
            _keep.append(_x)
    return ", ".join(_keep)


