    #     实测 `（2-4 解答随小问移除——完全同题，见 。）` —— 路径已剥，但句子残缺不可读，
    #     属用户所指「无用信息」的残渣。
    #     ⚠️⚠️ **铁律：`见/详见/参见` 必须是独立词首**（前导为行首/标点/空格），
    #        否则会命中「罕**见**」「由图可**见**」等**词内 `见`** → 误删正常答案行
    #        （实测误删 6 条：`极罕见。`、`由图可见：`、`常见：`…，P0）。
    #        且其后**必须只剩标点与右括号**（路径被剥空），正常行（`见下文`/`见附表`）不匹配。
    #        ⚠️⚠️ **`\s*$` 在 MULTILINE 下会吞换行**（`\s` 含 `\n`，`$` 匹配行尾）→ 会连带
    #        删掉下一行正常内容（记忆铁律 ⑨）。行级锚定一律用 `[ \t]*$`。
    a = re.sub(r"(?m)^(?!.*(?:!\[|\[\[))[^\n]*?(?<![\u4e00-\u9fa5])(?:详见|参见|见)"
               r"[：:，,。.、 \t]*[）)]?[ \t]*$", "", a)
    a = re.sub(r"(?m)^\*\*同源小问互链\*\*[^\n]*$\n?", "", a)
    a = re.sub(r"[ \t]+$", "", a, flags=re.M)
    a = re.sub(r"\n{3,}", "\n\n", a).strip()
    return fm, unwiki(q).strip(), unwiki(a).strip()


