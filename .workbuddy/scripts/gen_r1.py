def gate_v2(r, fm, q, a, rej):
    """卷面质量闸门 v2（2026-09-18）：结构质量门槛，替代旧「长度门槛」。

    返回 True = 通过；False = 拒收（并在 `rej` Counter 里记原因）。
    消费端：`gen_r1.py`（竞赛教材版）与 `gen_r1_mixed.py`（综合套卷）**共用同一门槛**。

    起因：用户反馈「套卷还是有很多无关和无用信息」。逐题分诊后发现，真正的杂质不是
    长度短，而是**三类结构缺陷**（实测 1203 个候选中招 110 题）：
      ① 题面 = 文件 H1 副标题（文件名派生的描述短语），根本不是题目。
        例：「碎裂化反应」「苯炔的 Ene 反应」「一些杂题」「闪式真空热解」
        —— ABOC 章末题「T*」系列与部分自学练习的通病：源文件 `## 题目` 段为空，
        `load()` 取到的就是 H1 标题文本。
      ② 纯指针：含「见原书」「图略」「自己画吧」「（待补充）」，学生无法作答。
      ③ **极短**指示词 + 清单缺失（题面只有一句指示词，清单误抄进 `## 参考答案` 段）。
    ⚠️ H1 须从**磁盘原文**读取：`load()` 已 drop_h1，q 里拿不到 H1。
    """
    _qs = q.strip()
    if re.search(r"见原书|图略|自己画吧|待补充|略，见源文件|原文未提供", _qs):
        rej["纯指针/无实质题干"] += 1
        return False
    _h1s = ""
    try:
        _raw = io.open(os.path.join(ROOT, r["_path"].replace("/", os.sep)),
                       encoding="utf-8", newline="").read()
        _m = re.search(r"(?m)^#\s+题-[^\n]*[：:]\s*([^\n]+?)\s*$", _raw)
        if _m:
            _h1s = re.sub(r"\s+", "", _m.group(1))
    except Exception:
        pass
    if _h1s and re.sub(r"\s+", "", _qs) == _h1s:
        # 题面 == H1 副标题：若含作答动词（写出/画出/计算/解释…）则是题目被压缩成一句话，
        # 尚可作答（如「写出以下反应的产物。」需配图，另有 imgs 闸门把关）；
        # 若无作答动词，则是纯描述短语 → 拒收。
        if not re.search(r"写出|画出|计算|解释|判断|说明|比较|回答|简述|试述|指出|证明|"
                         r"预测|圈出|命名|排序|讨论|作图|试判断|试计算|试分析|举例|完成|区分",
                         _qs):
            rej["题干为描述短语"] += 1
            return False
    if len(_qs) < 8:
        rej["题干过短"] += 1
        return False
    # ── 闸门 v2 补充：**极短**指示词 + 清单缺失（2026-09-18 实测 6 题）─────────
    # 病症：题面**只有一句指示词**（去掉标点 <25 字），本该跟一个编号清单
    #   （1./2./①②/(1)/9-1…），但**源文件把清单误抄进了 `## 参考答案` 段**
    #   （转录期错位，非生成器 bug）。后果：学生版只见「试计算下列两种粒子的
    #   德布罗意波长」而无对象 → **无法作答**。
    # 实例：`题-汇智-原子结构-9.md`（9-1/9-2 在答案侧）、`题-汇智-原子结构-18.md`
    #   （18-1/18-2/18-3 在答案侧）—— 已在 `09-审计报告/` 记为**源文件缺陷**。
    # ⚠️ 判据必须加「题面极短（<25 字）」这一条：汇智系列大量题目（原子结构-10、
    #   分子结构-20/26/27、晶体结构-5/20/31/51…）有**完整的自足引子**（给出前提
    #   与数据），小问在答案侧是**正确形态**；若按「指示词结尾」一刀切会误伤 20 题。
    if len(re.sub(r"[\W_]", "", _qs)) < 25 \
       and not re.search(r"(?m)^\s*(?:\d+[\.、)]|[（(]\d+[)）]|[①②③④⑤⑥⑦⑧⑨⑩])", _qs) \
       and re.search(r"(?m)^\s*(?:\d+\s*[-–—]\s*\d+|(?:\d+)[\.、)])", a[:160] or ""):
        rej["指示词结尾但清单缺失"] += 1
        return False
    # ── 闸门 v2 补充 C：**题面引图但图缺失**（2026-09-18 第二轮探针，31 题）─────────
    # 病症（`gate_v2` 的**图片维度盲区**）：题面写了「如下图 / 下图 / 如下左图 / 结构如图」
    #   但**题面主语法图引用数为 0** → 学生版只见「见下图」而无图，**无法作答**。
    #   与既有 `imgs_ok()` 互补：后者查「已引用的图是否存在」，本条查「该引图却没引」。
    # 实测覆盖：探针 31 题 100% 命中；连带命中上轮黑名单 3 题（共 34），无假阳性。
    # 豁免：**真题的「## 题目图示与结构参考」章节**是合法考试形态（题目说明 + 图示区），
    #   92 个真题文件属此形态 → 读**磁盘原文**判 `(?m)^##\s*题目图示` 或 `(?m)^##\s*图示`。
    #   ⚠️ **不按「是否真题」一刀切**：28/34 届 3 道真题**无图示区**者确属真缺陷，必须照收。
    # ⚠️ 该判据**只防新增**，不回溯现有产物（既有缺陷由 `EXCLUDE_PATHS` 兜底）。
    _q_img = len(re.findall(r"!\[\[|!\[[^\]]*\]\(", _qs))
    if _q_img == 0 and re.search(
            r"如下图|如图|下图|如下左图|如下右图|左图|右图|结构如图|图形如", _qs):
        _exempt = r["_path"].replace(os.sep, "/") in FIG_REF_OK
        try:
            if re.search(r"(?m)^##\s*题目图示|^##\s*图示", _raw):
                _exempt = True
        except Exception:
            pass
        if not _exempt:
            rej["题面引图但图缺失"] += 1
            return False
    if len(a) < 15 and not is_choice_ans(a):
        rej["答案过短"] += 1
        return False
    if len(q) > 4000:
        rej["题干过长"] += 1
        return False
    return True


