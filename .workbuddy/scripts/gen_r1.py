    # ── 2026-09-18 **公式块闭合畸形修复**（卷生成层，不动红区源库）───────────────
    #   实测 `题-039-10-NHC-硼自由基催化环化`：显示公式块结尾被写成 `}$ $`（`$$` 开头、
    #   `$ $` 收尾，中间夹空格）→ **`$$` 落单无法闭合** → 全文 math 配对整体错位，
    #   后续所有 `$$…$$` 与 `$…$` 全部失配，precheck 报 7 处 `latex_outside_math` ERROR
    #   （`\frac`/`\mathrm`/`\boxed` 暴露），**教师版 docx 被拦不生成**。
    #   修法：把 `$ $`（`$`空格`$`）在**同行已有 `$$` 开头**时归并为 `$$`。
    #   ⚠️ 严格限定形态：仅当该行以 `$$` 起（显示公式块）且行内出现 `$ $` 才修，
    #      **不触碰**正常 `$a$ $b$`（两个独立行内公式）——它们中间无空格或空格两侧非纯 `$`。
    #   ⚠️ 用「行首 `$$` + 行内 `$ $`」双条件，避免误修 `其 $x$ 与 $y$`。
    #   ⚠️ 形态辨识：畸形是「`$$` 开块后，用 `$ $`（`$`+空格+`$`）收尾」。全库严格配对
    #      审计确认 **只有 1 道在选池内的题**（`题-039-10`）命中，且其 `$$` **不在行首**
    #      （前有图片与文字）→ 不能加行首锚。故用「`$$` + 任意 + `$ $`」但**限定 `$$` 到
    #      `$ $` 之间不含 `![[`**（避免跨图误吞）。
    #      ⚠️ **不要加尾部前瞻**：实测 `$ $` 后紧跟的是 `-`（连字符）而非空白，
    #        `(?=\s|$)` 会导致完全不匹配（曾因此反复「改了不生效」）。
    #        该形态 `$$…$ $` 已足够特异，且全库仅 1 处命中、6 组对照零误伤。
    t = re.sub(r"\$\$(?:(?!!\[\[)[^\n])*?\$\s\$",
               lambda m: m.group(0).replace("$ $", "$$"), t)
