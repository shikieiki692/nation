    #       是「规范、少换题」，而非「卷卷满 40」。**质量排序优先于凑数**。
    #   保留 `MULTI` 表与 `route()` 的跨桶语义（首桶按 ORDER 先到先得），不改动。
    #   ⚠️ 若将来确需补足某桶，必须**先验证目标桶存在同质量替代**，否则重蹈覆辙。

    picked, taken = {}, set()
    for key in ORDER:
        cand = [(pp, r) for pp, r in buckets.get(key, [])
                if r["_path"] not in taken]
