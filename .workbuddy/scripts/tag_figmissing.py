TAIL = "但卡内无对应图像，题面不可自足，组卷前须回源补图或剔除。"


def block(kind, quote):
    if kind == "REF":
        return ("> [!warning] 题面缺图（不可组卷）：本题原文含图——「%s」——%s"
                % (quote, TAIL))
    return ("> [!warning] 题面缺图·教材插图引用（组卷前须回源补图）：本题题面引用——「%s」——"
            "卡内无对应图像，学生须持原书方可作答，组卷前须回源补图或改用文字等价表述。" % quote)


ok, skip, fail = 0, 0, []
for rel, kind, quote in ITEMS:
    p = os.path.join(ROOT, rel.replace("/", os.sep))
    if not os.path.isfile(p):
        fail.append((rel, "文件不存在"))
        continue
    t = io.open(p, encoding="utf-8-sig").read().replace("\r\n", "\n")
    if "题面缺图" in t or "组卷隔离" in t:
        skip += 1
        print("  SKIP 已标注:", rel.split("/")[-1][:44])
        continue
    b = block(kind, quote)
    # 插入点：题面区末尾（## 参考答案 之前；无则文件末尾）
    j = t.find("\n## 参考答案")
    if j > 0:
        pos = j
        new = t[:pos] + "\n" + b + "\n" + t[pos:]
        where = "参考答案前"
    else:
        new = t.rstrip("\n") + "\n\n" + b + "\n"
        where = "文件末尾"
    if WRITE:
        io.open(p, "w", encoding="utf-8", newline="\n").write(new)
    ok += 1
    print("  [%s] %s  → %s" % (kind, rel.split("/")[-1][:46], where))

print()
print("结果: 待写入=%d  跳过(已标注)=%d  失败=%d%s"
      % (ok, skip, len(fail), "" if WRITE else "  (dry-run，未写入)"))
for r, why in fail:
    print("  FAIL:", r, why)
