md.append("⇒ **入池 1518 → 1562（累计 +44）**；A 类 **271 → 207**；审计与组卷器池一致（243+574+745=1562）。\n")
md.append("### 8.4 待续：仍有 3 个源文件含答案可救（约 11 张）\n")
md.append("`无机化学一_课后习题11.9.pdf`（GM-09-01/02/03）、`260609-汇智…模拟试题5.pdf`（HZ-05-01/05/06）、")
