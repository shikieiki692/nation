md.append("### 6.1 表格残缺（组卷器缺陷，已修）\n")
md.append("`html_table_to_md()` 的「全跨度说明行」判据 `len(ne)==1 and len(r)-1 >= max(1, ncol-2)`，")
md.append("会把「**只有第一格有内容的数据行**」（如 `['1','','','']`）误判成说明行 ⇒ 数据行被逐行拆成段落。")
md.append("实测：卷 XI 5-2-1「Hund 规则」作答表在卷里只剩表头 + 散落的 `1/2/3/4/5/6`。\n")
md.append("**修正**＝改用**真实 colspan** 判定（该行唯一单元格 `colspan ≥ 表宽` 才算跨满整行）。")
md.append("⇒ 5-2-1 表格恢复 **4×7**；`题-CM-12-07`（卷 XI 第 10 题）表格恢复 **3×3**。\n")
md.append("### 6.2 页眉噪点图（源卡缺陷，已清 53 张）\n")
md.append("建卡切图时把源 PDF 的**页眉装饰**（二维码、卡通 logo、纯色块）一并切入了卡——")
md.append("卷 XI 第 10 题即含 1 张二维码 + 1 张卡通。\n")
md.append("**处置**：按「黑占比＋方形」筛出 67 张候选 ⇒ **逐张目检**（自动判据与正常结构图重叠，不可用）")
md.append("⇒ 确认 **53 张二维码**，从 **44 张卡**删除 **61 处**引用（表格内 `<td>` 置空以保结构）。")
md.append("断图复核：仍 146 处（**未新增**），全在退役目录。\n")
md.append("> ⚠️ 判据坑记录：二维码（黑占比 0.42–0.45）与**深色照片/晶体标注图**（0.45–0.52）特征重叠，")
md.append("> 纯自动筛会误删题目必需图（实测 `d31440a7` 实为晶体结构标注图 E/δ/γ/β/α、`210982ec` 为题面产物照片）。")
md.append("> **此类清理必须逐张目检。**\n")
md.append("### 6.3 修复后卷 XI 复核\n")
md.append("重出后：答案版 **图 61/61、表 16/16**；学生版 **图 23/23、表 5/5**；渲染目检 5-2-1 表格与第 10 题均正常。\n")

md.append("\n## 七、本轮追加修正：「公式未转录」闸收窄（原误杀率 ≈98%）\n")
md.append("原判据＝「题面含公式（`$`≥10）但答案**一个 `$` 都没有** ＋ 答案≥400 字 ⇒ 弃卡」。")
md.append("实测 52 张命中里 **51 张是误杀**：\n")
md.append("- **32 张**答案**全靠结构图**（公式在图里）——如 `题-BJLY-01-04` 的答案是 11 张 `bjly01_ans_q4_*` 结构图；")
md.append("- **19 张**答案用**纯文本**写公式——如 `S8 + 3AsF5 → [S8][AsF6]2`、`ΔG = RT ln(CR/Cl)`、`ρ = ZM/VNA = 8.798 g/cm3`；")
md.append("- 原案例（`aFE (1-a)FEr^2=k2(1 OHCOO θOH)eRT` 纯 ASCII 乱码）经查**已在此前治理中修掉**（`题-HYS-01-07` 现为含图正常卡）。\n")
md.append("**修正**：判据收窄为「长答案 ＋ **无图** ＋ 无 `$` ＋ **无中文**」才判乱码。")
md.append("⇒ 该闸 **52 → 0**；入池 **1518 → 1549（+31）**；A 类 **271 → 223**。审计与组卷器池一致（242+569+738=1549）。\n")
md.append("> 📌 判据设计教训：**「答案没有公式」不等于「答案缺失」**——公式可能在图里、也可能写成纯文本。")
md.append("> 判据必须叠加「无图」与「无中文」，否则会误杀大量正常卡。\n")

md.append("\n## 八、回源救卡：「源确缺答案」复核（视觉回源）\n")
md.append("对 94 张「源确缺答案」逐张**回源核验**（找同源答案册/讲评/解析，用**题面内容比对**定位）：\n")
md.append("### 8.1 核验结论：绝大多数标注正确\n")
md.append("- 伽马「暑期模拟 8」：目录内 1–7、9、10 均有答案册，**唯独缺 8** ⇒ 标注正确；")
md.append("- 质心 UChO「10th」：答案合集只有 1st–9th ⇒ 标注正确；")
md.append("- 其余多匹配到**纯试题**（无答案关键词）⇒ 标注正确。\n")
md.append("### 8.2 ★ 已救回：伽马 GM-25 系列 9 张\n")
md.append("`gamma晶体结构习题.pdf` 实为「**题目＋答案**」合订（答案在**下一题标题所在页的页首**）。")
