md.append("`题-GM-25-01` 经核**源文件确实未给第 1 题答案**（第 1、2 题题干同页）⇒ 回滚为「源确缺答案」。\n")
md.append("### 8.3 连带修正两处闸门误杀\n")
md.append("| 闸门 | 误杀原因 | 修正 |\n|:--|:--|:--|\n")
md.append("| 题面泄露 | `LEAK` 命中**题目标题行的分值**「（12 分，占 8%）」（GM-25 等 15 张） | 判前**剔除标题行** |\n")
