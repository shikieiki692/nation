t = io.open(P, encoding='utf-8-sig').read()
blocks = re.split(r'(?=^### 第 \d+ 题)', t, flags=re.M)
out = []
done = []
for b in blocks:
    m = re.match(r'^### 第 (\d+) 题', b)
    if not m or int(m.group(1)) not in ANALYSES:
        out.append(b)
        continue
    n = int(m.group(1))
    if '—— 解析 ——' in b:
        out.append(b)
        continue
    a = ANALYSES[n]
    # 知识点页存在性校验
    missing = [k for k in a['kps'] if k not in KP]
    if missing:
        print('  ⚠️ 第 %d 题 知识点页缺失：%s' % (n, missing))
        sys.exit(3)
    kp_line = '> **考点**：%s（知识点：%s）' % (a['kp'], '、'.join('〈%s〉' % k for k in a['kps']))
    block = '> —— 解析 ——\n>\n' + kp_line + '\n>\n> **思路**：' + a['idea'] + '\n'
    # 插到块尾（去尾部空白后，若以 --- 结尾则插在它之前）
    stripped = b.rstrip('\n')
    if stripped.endswith('---'):
        head = stripped[:-3].rstrip('\n')
        newb = head + '\n\n' + block + '\n---\n\n'
    else:
        head = stripped
        newb = stripped + '\n\n' + block + '\n'
    # 断言：仅尾部追加，头部逐字未变
    assert newb.startswith(head), '第 %d 题头部被改动' % n
    out.append(newb)
    done.append(n)

print('待插入 =', sorted(done))
if not APPLY:
    print('(dry-run；加 --apply)')
    sys.exit(0)

new = ''.join(out)
assert new.count('—— 解析 ——') == 10, new.count('—— 解析 ——')
# 断言：删除全部插入块后，应与原文逐字一致
tmp = new
for n in sorted(done):
    a = ANALYSES[n]
    blk = ('> —— 解析 ——\n>\n> **考点**：%s（知识点：%s）\n>\n> **思路**：%s\n'
           % (a['kp'], '、'.join('〈%s〉' % k for k in a['kps']), a['idea']))
    assert blk in tmp, '第 %d 题插入块未找到' % n
    tmp = tmp.replace('\n\n' + blk + '\n', '\n\n', 1)
assert [l for l in tmp.split('\n') if l.strip()] == [l for l in t.split('\n') if l.strip()], \
    '删除插入块后非空行序列不一致'
print('断言通过：删块后非空行与原文逐行一致')
bak = '.workbuddy/tmp/opt_pipe/_bak/xvii_%s' % __import__('datetime').datetime.now().strftime('%Y%m%d_%H%M%S')
os.makedirs(bak, exist_ok=True)
shutil.copy2(P, os.path.join(bak, os.path.basename(P)))
io.open(P, 'w', encoding='utf-8', newline='').write(new)
print('已写盘；备份 %s' % bak)
print('解析块数 =', new.count('—— 解析 ——'))
